#!/usr/bin/env node
// Generates docs/COMMANDS.md — a complete, machine-friendly reference of every
// command, argument and flag, built straight from the command registry so it
// never drifts from `nimbuz --help`. Run: npm run docs
import { writeFileSync, mkdirSync } from "node:fs";

import { buildRoot, VERSION } from "../src/cli.js";
import { setColorEnabled } from "../src/core/colors.js";
import { GLOBAL_FLAGS } from "../src/core/registry.js";

setColorEnabled(false);

const esc = (s = "") => String(s).replace(/\|/g, "\\|");

function flagLabel(spec) {
  const value = spec.type === "boolean" ? "" : ` <${spec.placeholder || (spec.type === "number" ? "n" : "value")}>`;
  const repeat = spec.type === "list" ? " …" : "";
  return `${spec.alias ? `-${spec.alias}, ` : ""}--${spec.name}${value}${repeat}`;
}

function flagTable(specs) {
  const rows = specs.filter((s) => !s.hidden).map((s) => {
    const extra = [];
    if (s.choices) extra.push(`one of: ${s.choices.join(", ")}`);
    if (s.default !== undefined && s.type !== "boolean" && s.type !== "list") extra.push(`default: ${s.default}`);
    return `| \`${esc(flagLabel(s))}\` | ${esc(s.desc)}${extra.length ? ` _(${esc(extra.join("; "))})_` : ""} |`;
  });
  return rows.length ? ["| Flag | Description |", "| --- | --- |", ...rows].join("\n") : "";
}

function usage(node, words) {
  const parts = ["nimbuz", ...words];
  if (node.commands && !node.run) parts.push("<command>");
  for (const arg of node.args ?? []) {
    const name = arg.variadic ? `${arg.name}...` : arg.name;
    parts.push(arg.required ? `<${name}>` : `[${name}]`);
  }
  parts.push("[flags]");
  return parts.join(" ");
}

const sections = [];
const index = [];

function walk(node, words, depth) {
  for (const child of node.commands ?? []) {
    if (child.hidden) continue;
    const path = [...words, child.name];
    const title = `nimbuz ${path.join(" ")}`;
    const anchor = title.toLowerCase().replace(/[^a-z0-9 -]/g, "").replace(/ /g, "-");
    index.push(`${"  ".repeat(depth)}- [\`${title}\`](#${anchor}) — ${child.summary ?? ""}`);

    const out = [`${"#".repeat(Math.min(depth + 3, 6))} \`${title}\``, "", child.description || child.summary || ""];
    if (child.aliases?.length) out.push("", `**Aliases:** ${child.aliases.map((a) => `\`${a}\``).join(", ")}`);
    out.push("", "```text", usage(child, path), "```");
    if (child.args?.length) {
      out.push("", "| Argument | Description | Required |", "| --- | --- | --- |");
      for (const a of child.args) out.push(`| \`${a.name}${a.variadic ? "..." : ""}\` | ${esc(a.desc)} | ${a.required ? "yes" : "no"} |`);
    }
    if (child.flags?.length) out.push("", flagTable(child.flags));
    if (child.commands?.length) {
      out.push("", "**Subcommands:** " + child.commands.filter((c) => !c.hidden).map((c) => `\`${c.name}\``).join(" · "));
    }
    if (child.examples?.length) {
      out.push("", "```bash", ...child.examples.map((e) => (e.startsWith("#") ? e : e)), "```");
    }
    sections.push(out.join("\n"));
    walk(child, path, depth + 1);
  }
}

walk(buildRoot(), [], 0);

const doc = `<!-- AUTO-GENERATED by scripts/gen-docs.js from the command registry. Do not edit by hand. -->
# Nimbuz CLI — Command Reference

Complete reference for \`@nimbuz/cli\` v${VERSION}. Every command, argument and flag below is generated from the
same registry that powers \`nimbuz --help\`, so it is always accurate for this version.

## Global flags

These flags work with every command.

${flagTable(GLOBAL_FLAGS)}

## Index

${index.join("\n")}

## Commands

${sections.join("\n\n---\n\n")}
`;

mkdirSync(new URL("../docs/", import.meta.url), { recursive: true });
writeFileSync(new URL("../docs/COMMANDS.md", import.meta.url), doc);
console.log(`docs/COMMANDS.md written (${index.length} commands)`);
